// Função de multiplicação tipada
function multiplicar(a: number, b: number): number {
  return a * b;
}

// Função de saudação tipada
function saudacao(nome: string): string {
  return `Olá ${nome}`;
}

// Testes no console
console.log(multiplicar(4, 5));     // 20
console.log(saudacao("Flávia"));   // Olá Flávia
